    /**
     * الحصول على القالب الافتراضي المناسب لنوع المستند
     */
    public static function getDefaultTemplate(string|OfferType|null $type): string
    {
        $value = $type instanceof OfferType ? $type->value : ($type ?? 'quotation');

        return match ($value) {
            OfferType::UNIFIED_CONTRACT->value, 'unified_contract' => static::getUnifiedContractTemplate(),
            OfferType::AGREEMENT_CONTRACT->value, 'agreement_contract' => static::getAgreementContractTemplate(),
            OfferType::SALE_AGREEMENT->value, 'sale_agreement' => static::getSaleAgreementTemplate(),
            OfferType::SUPPLY_OFFER->value, 'supply_offer' => static::getSupplyOfferTemplate(),
            default => static::getQuotationTemplate(),
        };
    }

